// دالة ذكية لاختيار آية اليوم بالتتابع حسب تاريخ اليوم
window.getTodayVerse = function() {
  try {
    var verses = window.DAILY_VERSES;
    if (!verses || !verses.length) {
      return {
        text: "الْمَقَاصِدُ تَبْطُلُ مِنْ عَدَمِ الْمَشُورَةِ، وَبِكَثْرَةِ الْمُشِيرِينَ تَقُومُ.",
        ref: "أمثال 15: 22"
      };
    }
    // حساب رقم اليوم من بداية السنة ليتغير كل يوم آية جديدة بنظام دوري
    var now = new Date();
    var start = new Date(now.getFullYear(), 0, 0);
    var diff = (now - start) + ((start.getTimezoneOffset() - now.getTimezoneOffset()) * 60 * 1000);
    var oneDay = 1000 * 60 * 60 * 24;
    var dayOfYear = Math.floor(diff / oneDay);
    var index = dayOfYear % verses.length;
    return verses[index] || verses[0];
  } catch (e) {
    return window.DAILY_VERSES[0];
  }
};
